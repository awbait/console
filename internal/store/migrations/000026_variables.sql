-- Глобальные переменные платформы: именованные значения, на которые ссылается
-- документ версии сервиса.
--
-- Документ версии описывает форму заказа и значения, которые портал проставляет
-- сам. Часть таких значений не принадлежит ни чарту, ни заказу: домен, в котором
-- живёт стенд, имя дежурной команды, префикс окружения. Их знает платформенная
-- команда, и меняются они отдельно от чартов, поэтому лежат здесь, а не в
-- документе, который пришлось бы править и заново согласовывать в каждом сервисе.
--
-- Это не хранилище секретов: значение уезжает в values.yaml в Git и видно всем,
-- у кого есть доступ к репозиторию заказов.
CREATE TABLE IF NOT EXISTS variables (
  -- Имя, которым на переменную ссылается документ версии: "{{.Vars.OPS}}".
  -- Верхний регистр и подчёркивание - чтобы ссылка на переменную читалась в
  -- документе иначе, чем ссылка на поле заказа ("{{.Team}}").
  name        TEXT PRIMARY KEY CHECK (name ~ '^[A-Z][A-Z0-9_]{0,63}$'),
  value       TEXT NOT NULL DEFAULT '',
  -- Зачем переменная нужна: показывается владельцу сервиса в подсказке
  -- конструктора, где он выбирает, на что сослаться.
  description TEXT NOT NULL DEFAULT '',
  -- Кто менял в последний раз (OIDC sub) и когда. Истории значений нет: она
  -- нужна для расследования, а расследование идёт по коммитам в Git, куда
  -- значение и уехало.
  updated_by  TEXT NOT NULL DEFAULT '',
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
